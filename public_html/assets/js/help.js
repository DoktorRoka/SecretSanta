/**
 * Подсказка «Как это работает»: объясняет разницу между паролем
 * организатора и паролем для входа. Кнопку можно ставить на любом экране.
 */

import { el, openModal } from './ui.js';
import { icon } from './icons.js';

function block(title, ...paragraphs) {
    const nodes = [el('h3', { class: 'subheading', text: title })];
    for (const text of paragraphs) {
        nodes.push(el('p', { class: 'hint', text }));
    }
    return nodes;
}

export function openHelp() {
    const body = [
        el('p', {
            class: 'lead',
            text: 'В комнате два разных пароля. Они открывают разные вещи — не перепутайте.',
        }),
        ...block(
            'Код комнаты',
            'Короткий код, который организатор создаёт вместе с комнатой и рассылает участникам. Он нужен всем, поэтому секретом не является.',
        ),
        ...block(
            'Пароль для входа (у каждого свой)',
            'Личный пароль участника. Вход со страницы «Вход в кабинет»: код комнаты + ваш контакт (Telegram или телефон) + этот пароль.',
            'После жеребьёвки в кабинете видно, кому вы дарите подарок. Регистрируясь, участник придумывает пароль для входа сам.',
        ),
        ...block(
            'Пароль организатора',
            'Пароль для служебной панели комнаты. Вход со страницы «Панель организатора»: код комнаты + этот пароль.',
            'Он открывает список участников, сброс ПИН, удаление участника и запуск жеребьёвки. Организатору его не нужно сообщать участникам.',
        ),
        el('p', {
            class: 'warning-text',
            text: 'Вы организатор и участник одновременно, поэтому задаёте оба пароля: пароль организатора — для панели, пароль для входа — для своего кабинета. Они могут совпадать, но надёжнее сделать их разными.',
        }),
        el('p', {
            class: 'hint',
            text: 'Жеребьёвка честная: кто кому дарит, не видит никто — ни участники, ни организатор, ни суперадминистратор. Каждый видит только своего получателя. После жеребьёвки всем нужно войти в кабинет заново.',
        }),
        ...block(
            'Если пароль забыт',
            'Участнику: пока не проведена жеребьёвка, организатор в панели нажимает «Сбросить ПИН» и передаёт временный ПИН — после входа система попросит задать новый пароль. После жеребьёвки сброс ПИН недоступен.',
            'Организатору: пароль организатора может сбросить только суперадминистратор мероприятия.',
        ),
    ];

    const modal = openModal({ title: 'Как это работает', body });
    const done = el('button', { class: 'btn btn-primary', type: 'button', text: 'Понятно' });
    done.addEventListener('click', modal.close);
    modal.dialog.querySelector('.modal-actions').append(done);
    return modal;
}

export function helpButton(label = 'Как это работает', className = 'btn btn-ghost') {
    const button = el('button', { class: className, type: 'button' }, [
        icon('info'),
        el('span', { text: label }),
    ]);
    button.addEventListener('click', (event) => {
        event.preventDefault();
        openHelp();
    });
    return button;
}